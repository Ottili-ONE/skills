"""Catalogue drift guard (SKL-W0-01, TASK-0002).

``catalog.json`` is GENERATED from the ``skills/`` folders by
``scripts/gen-catalog.mjs`` — it is never hand-edited. This test regenerates the
catalogue into a temporary file and compares it with the committed one, so any
drift (a skill folder that is missing from the catalogue, a stale file list, a
hand-edited entry) fails instead of going unnoticed.

Where the ``package`` field comes from
-------------------------------------
The ``package`` of an entry is the name of the folder that CONTAINS the skill
folder, i.e. for ``skills/<package>/<skill-name>/SKILL.md`` the package is
``<package>``. It is derived from the folder layout on disk by the generator —
never from the SKILL.md frontmatter and never from a hand-maintained list. The
same rule is asserted in ``test_package_field_comes_from_the_skill_folder`` so
that the generator and this test can never disagree about it.
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GENERATOR = ROOT / "scripts" / "gen-catalog.mjs"
CATALOG = ROOT / "catalog.json"
SKILLS_DIR = ROOT / "skills"


def run_generator(out_file: Path) -> str:
    """Run the catalogue generator into ``out_file`` and return its stdout."""
    result = subprocess.run(
        ["node", str(GENERATOR), "--out", str(out_file)],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, (
        f"generator failed (rc={result.returncode})\n"
        f"stdout: {result.stdout}\nstderr: {result.stderr}"
    )
    return result.stdout


def skill_folders_on_disk() -> set[tuple[str, str]]:
    """Every (package, skill) pair that has a SKILL.md on disk."""
    found: set[tuple[str, str]] = set()
    for skill_md in SKILLS_DIR.glob("*/*/SKILL.md"):
        rel = skill_md.parent.relative_to(ROOT)
        found.add((rel.parts[1], rel.parts[2]))
    return found


def test_committed_catalog_matches_the_generated_one(tmp_path: Path) -> None:
    """catalog.json is byte-identical to a fresh generation — no hand edits, no drift."""
    generated = tmp_path / "catalog.json"
    run_generator(generated)
    assert generated.read_text(encoding="utf-8") == CATALOG.read_text(encoding="utf-8"), (
        "catalog.json is out of date: it is generated by scripts/gen-catalog.mjs. "
        "Run `node scripts/gen-catalog.mjs` and commit the result."
    )


def test_generator_output_is_deterministic(tmp_path: Path) -> None:
    """Two generations of the same tree produce the same bytes (no wall-clock stamp)."""
    first = tmp_path / "first.json"
    second = tmp_path / "second.json"
    run_generator(first)
    run_generator(second)
    assert first.read_bytes() == second.read_bytes()


def test_catalogue_has_no_wall_clock_stamp() -> None:
    """A generated artefact must not carry a timestamp: it would drift every day."""
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    assert "updated_at" not in catalog, (
        "catalog.json must not contain a wall-clock stamp; the catalogue has to be "
        "reproducible byte-for-byte from the skills/ folders."
    )


def test_package_field_comes_from_the_skill_folder(tmp_path: Path) -> None:
    """The package of an entry is the folder that contains the skill folder."""
    generated = tmp_path / "catalog.json"
    run_generator(generated)
    catalog = json.loads(generated.read_text(encoding="utf-8"))

    assert catalog["skills"], "the catalogue lists no skills at all"
    for entry in catalog["skills"]:
        parts = Path(entry["path"]).parts
        assert parts[0] == "skills" and len(parts) == 3, entry["path"]
        package, skill = parts[1], parts[2]
        assert entry["package"] == package, (
            f"{entry['id']}: package '{entry['package']}' does not match the folder "
            f"that contains the skill folder ('{package}')"
        )
        assert entry["name"] == skill, (
            f"{entry['id']}: name '{entry['name']}' does not match the skill folder "
            f"name ('{skill}')"
        )


def test_catalogue_lists_every_skill_folder(tmp_path: Path) -> None:
    """Every skills/<package>/<skill>/ folder appears exactly once in the catalogue."""
    generated = tmp_path / "catalog.json"
    run_generator(generated)
    catalog = json.loads(generated.read_text(encoding="utf-8"))

    listed = [(entry["package"], entry["name"]) for entry in catalog["skills"]]
    assert len(listed) == len(set(listed)), "the catalogue contains duplicate skills"
    assert set(listed) == skill_folders_on_disk(), (
        "the catalogue and the skills/ folders disagree: "
        f"missing={sorted(skill_folders_on_disk() - set(listed))} "
        f"unknown={sorted(set(listed) - skill_folders_on_disk())}"
    )


def test_generator_refuses_an_unknown_option(tmp_path: Path) -> None:
    """An unknown option is an error, never a silent fallback.

    The generator used to ignore every option it did not know, so a typo
    (``--chek`` instead of ``--check``) silently WROTE the catalogue instead
    of checking it.
    """
    out_file = tmp_path / "catalog.json"
    result = subprocess.run(
        ["node", str(GENERATOR), "--chek", "--out", str(out_file)],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 2, (
        f"an unknown option must be refused (rc={result.returncode})\n"
        f"{result.stdout}{result.stderr}"
    )
    assert "unknown option" in result.stderr
    assert not out_file.exists(), "a refused invocation must not write the catalogue"


def test_generator_refuses_an_out_option_without_a_value(tmp_path: Path) -> None:
    """``--out`` without a file path is a usage error, not a crash."""
    result = subprocess.run(
        ["node", str(GENERATOR), "--out"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 2, (
        f"--out without a value must be refused (rc={result.returncode})\n"
        f"{result.stdout}{result.stderr}"
    )
    assert "--out needs a file path" in result.stderr
    assert "TypeError" not in result.stderr, "the usage error must not be a stack trace"
