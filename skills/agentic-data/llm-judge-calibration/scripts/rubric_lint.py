#!/usr/bin/env python3
"""Lint a judge rubric for the structural requirements of llm-judge-calibration.

A rubric that passes this check still needs calibration, but a rubric that fails
it cannot be calibrated at all: score points without examples produce 20+ point
spread on re-annotation, and points without anti-examples cannot distinguish
adjacent scores.

Usage:
    python3 scripts/rubric_lint.py rubric.yaml            # exit 0 if clean
    python3 scripts/rubric_lint.py --json report.json rubric.yaml

Reads YAML. Fully offline and deterministic.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - exercised only when PyYAML is absent
    yaml = None


def _die(msg: str, code: int = 2) -> int:
    print(f"ERROR: {msg}", file=sys.stderr)
    return code


def load_rubric(path: Path) -> dict:
    if not path.is_file():
        raise SystemExit(f"ERROR: rubric file not found: {path}")
    text = path.read_text(encoding="utf-8")
    if yaml is None:
        # Minimal YAML subset: this file is generated by gen_calibration.py and
        # is always valid YAML, so a missing PyYAML is a hard failure, not a
        # degraded one.
        raise SystemExit("ERROR: PyYAML is required to lint rubrics")
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise SystemExit(f"ERROR: rubric is not valid YAML: {exc}")
    if not isinstance(data, dict):
        raise SystemExit("ERROR: rubric must be a mapping at the top level")
    return data


def lint_rubric(rubric: dict) -> tuple[list[str], dict]:
    failures: list[str] = []
    info: dict = {"rubric_id": rubric.get("rubric_id"), "n_points": 0}

    points = rubric.get("points")
    if not isinstance(points, list) or not points:
        failures.append("FAIL: rubric has no 'points' list")
        return failures, info

    info["n_points"] = len(points)
    scores_seen: set[int] = set()
    prev_score: int | None = None
    for i, p in enumerate(points):
        if not isinstance(p, dict):
            failures.append(f"FAIL: point {i} is not a mapping")
            continue
        score = p.get("score")
        if not isinstance(score, int):
            failures.append(f"FAIL: point {i} has no integer 'score'")
            continue
        if score in scores_seen:
            failures.append(f"FAIL: duplicate score {score}")
        scores_seen.add(score)
        if prev_score is not None and score != prev_score + 1:
            failures.append(f"FAIL: scores are not contiguous at point {i} "
                            f"({prev_score} -> {score})")
        prev_score = score

        definition = p.get("definition")
        if not isinstance(definition, str) or not definition.strip():
            failures.append(f"FAIL: point {score} has no 'definition'")

        example = p.get("example")
        if not isinstance(example, str) or not example.strip():
            failures.append(f"FAIL: point {score} has no 'example'")

        anti = p.get("anti_examples")
        if score != min(scores_seen) and not isinstance(anti, list):
            failures.append(f"FAIL: point {score} has no 'anti_examples' list")
        elif isinstance(anti, list) and score != min(scores_seen) and not anti:
            failures.append(f"FAIL: point {score} has empty 'anti_examples'")

    if scores_seen and min(scores_seen) != 1:
        failures.append(f"FAIL: lowest score is {min(scores_seen)}, expected 1")

    info["scores"] = sorted(scores_seen)
    info["complete"] = not failures
    return failures, info


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("rubric", type=Path)
    ap.add_argument("--json", type=Path, default=None)
    args = ap.parse_args()

    rubric = load_rubric(args.rubric)
    failures, info = lint_rubric(rubric)

    for f in failures:
        print(f, file=sys.stderr)
    if args.json:
        args.json.write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")

    if failures:
        print(f"FAIL: rubric has {len(failures)} problem(s)", file=sys.stderr)
        return 1
    print(f"PASS: rubric '{info.get('rubric_id')}' has {info['n_points']} "
          f"contiguous points with definitions, examples and anti-examples",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
