#!/usr/bin/env python3
"""Generate deterministic eval-harness fixtures for verifiable-environments.

The scratch fixtures used by the tests are generated by this script so that
good/broken/lazy agents are reproducible and auditable. Run offline:

    python3 scripts/gen_fixtures.py --out <dir>

The good agent writes output.json (status ok) and summary.md (>=20 words).
The broken agent writes nothing. The lazy agent writes an empty output.json.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

SPEC_TEXT = """# SPEC: file-writing task

The agent must produce, in its sandbox output directory:

1. `output.json` — a JSON object with field `status` equal to the string `ok`.
2. `summary.md` — a markdown file of at least 20 words describing the output.

Observable outcomes only. Nothing else is checked.
"""

CONTRACT = {"network": "deny", "filesystem": "scoped", "exec": "allowlisted",
            "time_seconds": 300, "secrets": "none"}
CONTRACT_BROKEN = {"network": "allow", "filesystem": "open", "exec": "allow",
                   "time_seconds": 0, "secrets": "full"}

CHECKS = {"checks": [
    {"name": "output_file", "path": "output.json", "exists": True,
     "json_field": "status", "json_value": "ok",
     "spec_ref": "output.json — a JSON object with field status equal to the string ok"},
    {"name": "summary_file", "path": "summary.md", "exists": True,
     "spec_ref": "summary.md — a markdown file of at least 20 words describing the output"},
]}

SUMMARY_GOOD = ("The agent wrote output.json with status set to ok and confirmed "
                "the result in a summary file as required by the task specification.")


def write_agent(out: Path, output_json: str | None, summary: str | None) -> None:
    out.mkdir(parents=True, exist_ok=True)
    if output_json is not None:
        (out / "output.json").write_text(output_json, encoding="utf-8")
    if summary is not None:
        (out / "summary.md").write_text(summary, encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    out: Path = args.out
    if out.exists():
        print(f"FAIL: output dir already exists: {out}", file=sys.stderr)
        return 1
    out.mkdir(parents=True)

    (out / "SPEC.md").write_text(SPEC_TEXT, encoding="utf-8")
    (out / "contract.json").write_text(json.dumps(CONTRACT, indent=2) + "\n", encoding="utf-8")
    (out / "contract_broken.json").write_text(json.dumps(CONTRACT_BROKEN, indent=2) + "\n", encoding="utf-8")
    (out / "checks.json").write_text(json.dumps(CHECKS, indent=2) + "\n", encoding="utf-8")

    write_agent(out / "good", json.dumps({"status": "ok"}), SUMMARY_GOOD)
    write_agent(out / "broken", None, None)
    write_agent(out / "lazy", json.dumps({"status": "ok"}), None)

    # A neutered check set for the verify-the-verifier step: the live checks with
    # exactly one check flipped to always-pass (it asserts a marker file no agent
    # creates, with exists=False, so it passes for good, broken and lazy alike).
    # Flipping summary_file is decisive: the lazy agent writes output.json but no
    # summary, so a live summary check is the only thing between it and a perfect
    # score. With summary neutered, the lazy agent passes everything and power
    # collapses to 0 vs lazy -- proving the harness detects a dead check.
    neutered = {"checks": [
        dict(c) for c in CHECKS["checks"]
        if c["name"] != "summary_file"
    ] + [{
        "name": "summary_file_neutered",
        "path": "__neutered_marker__",
        "exists": False,
        "spec_ref": "verify-the-verifier: this check is intentionally always-pass",
    }]}
    (out / "checks_neutered.json").write_text(json.dumps(neutered, indent=2) + "\n", encoding="utf-8")
    print(f"PASS: fixtures written to {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
