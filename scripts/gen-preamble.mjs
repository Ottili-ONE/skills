#!/usr/bin/env node
// gen-preamble.mjs — generate skills/orchestrator-preamble/references/preamble.md
//
// Reproducible: the same canonical skill set on disk always produces the same file.
// The generator takes no input beyond the four canonical engineering skills; it reads
// each skill's "Run the offline gate" rule line and emits one imperative rule each.
//
// Usage:
//   node scripts/gen-preamble.mjs                # write preamble.md
//   node scripts/gen-preamble.mjs --check         # exit 0 if committed file matches

import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const OUT = resolve(REPO, 'skills', 'orchestrator-preamble', 'orchestrator-preamble', 'references', 'preamble.md');

// Canonical skills, in rule order. Each entry: the skill dir + the exact gate command
// as it appears in that skill's SKILL.md "Run the offline gate" line.
const CANONICAL = [
  {
    name: 'company_id / RLS',
    skill: 'skills/engineering/pg-rls-multitenant',
    gate: 'python3 scripts/check_rls_migration.py <migration.sql>',
    summary:
      'every tenant table carries `company_id` (or the repo\'s tenant discriminator), ' +
      '`FORCE ROW LEVEL SECURITY` is set, a `USING`/`WITH CHECK` policy exists, and the ' +
      'grant is scoped. Any finding is a merge blocker.',
  },
  {
    name: 'outbox',
    skill: 'skills/engineering/outbox-idempotency',
    gate: 'python3 scripts/check_outbox.py <sql-file>',
    summary:
      'any write that outlives the request goes through an outbox table with a UNIQUE ' +
      '`idempotency_key`, the business write and the outbox INSERT are in ONE transaction, ' +
      'the poller uses `ORDER BY created_at ... FOR UPDATE SKIP LOCKED`, and poison ' +
      'messages are moved to `poison_outbox` (never deleted).',
  },
  {
    name: 'problem+json',
    skill: 'skills/engineering/problem-json-contracts',
    gate: 'python3 scripts/check_problem_catalogue.py --catalogue <cat> --openapi <spec> --schema-dir <dir>',
    summary:
      'every HTTP >=400 response is RFC 9457 `application/problem+json` with an absolute ' +
      '`type` URI, a `status` equal to the HTTP code, a catalogue code that matches the ' +
      'JSON Schema `enum` exactly, and `retry_after` as integer seconds for retriable errors.',
  },
  {
    name: 'honest status',
    skill: 'skills/engineering/honest-status',
    gate: 'python3 scripts/check_status_evidence.py STATUS.md --root .',
    summary:
      '"done" means a command ran, you saw its exit code, and the log path is recorded. ' +
      'A claim without a runnable evidence pointer is FALSE_DONE, never DONE.',
  },
];

function assertGatePresent(entry) {
  const skillMd = resolve(REPO, entry.skill, 'SKILL.md');
  if (!existsSync(skillMd)) {
    throw new Error(`canonical skill missing: ${skillMd}`);
  }
  const text = readFileSync(skillMd, 'utf8');
  if (!text.includes(entry.gate)) {
    throw new Error(
      `${entry.skill}/SKILL.md does not contain the expected gate command: ${entry.gate}`
    );
  }
}

function render() {
  for (const e of CANONICAL) assertGatePresent(e);

  const lines = [];
  lines.push('# Orchestrator Preamble (generated)');
  lines.push('');
  lines.push(
    '> Generated by `scripts/gen-preamble.mjs` from the canonical engineering skills. ' +
    'Do not hand-edit — regenerate with `node scripts/gen-preamble.mjs`. ' +
    '"Done" means a command ran, you saw its exit code, and the log path is recorded.'
  );
  lines.push('');
  for (let i = 0; i < CANONICAL.length; i++) {
    const e = CANONICAL[i];
    lines.push(`${i + 1}. **${e.name}** — ${e.summary} Check: \`${e.gate}\` — exit 0 means the check passes; any finding is a merge blocker.`);
    lines.push('');
  }
  // Trim trailing blank line, keep a single trailing newline.
  while (lines.length && lines[lines.length - 1] === '') lines.pop();
  return lines.join('\n') + '\n';
}

const check = process.argv.includes('--check');
const body = render();

if (check) {
  if (!existsSync(OUT)) {
    console.error(`preamble missing: ${OUT}`);
    process.exit(1);
  }
  const committed = readFileSync(OUT, 'utf8');
  if (committed !== body) {
    console.error('preamble.md is stale — run `node scripts/gen-preamble.mjs`');
    process.exit(1);
  }
  console.log('preamble.md is up to date');
  process.exit(0);
}

writeFileSync(OUT, body, 'utf8');
console.log(`wrote ${OUT} (${body.split('\n').length} lines)`);
